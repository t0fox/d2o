/* d2k_quicconn.h — ОДНО СОЕДИНЕНИЕ QUIC, ровно настолько, насколько нужно
 * зонду подтверждения.
 *
 * ЧТО ЭТО. Клиент QUIC версии 1, доводящий рукопожатие до прикладных ключей и
 * умеющий послать и принять данные по потоку. Поверх него живёт HTTP/3
 * (core/h3.c), а поверх того — зонд (core/verify.c).
 *
 * ГРАНИЦЫ ОБЪЯВЛЕНЫ ПРЯМО, а не «пока не сделано». Зонд живёт одно
 * рукопожатие и один запрос, около двух секунд, и из этого следует ВСЁ
 * остальное:
 *
 *   НЕТ управления перегрузкой. Мы шлём три-четыре датаграммы и в окно не
 *   упрёмся ни при каких обстоятельствах.
 *   НЕТ обнаружения потерь по порогу пакетов — только таймер PTO с
 *   фиксированным стартовым RTT (RFC 9002 §6.2.2 задаёт 333 мс до первого
 *   замера) и удвоением.
 *   НЕТ обновления ключей (quic ku), 0-RTT, миграции пути и stateless reset.
 *   НЕТ контроля потока сверх объявленных пределов: мы качаем килобайты, а
 *   объявляем мегабайт. Это про НАШИ пределы. Пределы СЕРВЕРА, наоборот,
 *   читаются и соблюдаются (задача 29): поток с номером выше его
 *   initial_max_streams_bidi — это STREAM_LIMIT_ERROR, то есть замер, который
 *   не состоится, а выглядеть будет нехваткой времени.
 *
 * Каждый пункт — не «упрощение на будущее», а решение, за которым стоит срок
 * жизни зонда. Если зонд когда-нибудь станет жить долго, эти строки придётся
 * переписать, а не дописать.
 *
 * ЧЕГО СРЕЗАТЬ БЫЛО НЕЛЬЗЯ и почему: подтверждения уровня Handshake (без них
 * сервер упирается в предел троекратного усиления и замолкает — на замере это
 * неотличимо от блокировки), добивка первой датаграммы до 1200 байт,
 * восстановление номера пакета, Retry, обход коалесцированных пакетов и
 * transport parameters. Каждый из шести молча превращает «работает» в
 * «сервер молчит».
 */
#ifndef D2K_QUICCONN_H
#define D2K_QUICCONN_H

#include <stddef.h>
#include "d2k_quicsnap.h"
#include <stdint.h>

typedef struct d2k_qc d2k_qc;

typedef struct {
    const char *ip;        /* адрес цели, IPv4 текстом */
    uint16_t    port;      /* обычно 443 */
    const char *sni;       /* имя для расширения server_name и сверки сертификата */
    const char *alpn;      /* "h3"; NULL — без ALPN (сервер вправе отказать) */
    int         deadline_ms; /* потолок на ВСЁ рукопожатие */
    size_t      pad_to;    /* добить ClientHello до этой длины; 0 — не добивать */
    /* ФОРМА ПРИВЕТСТВИЯ КЛИЕНТА (задача 66). NULL — как раньше: одно
       минимальное приветствие в одной датаграмме. Иначе ClientHello добивается
       до form->ch_len, а первый полёт уходит form->n датаграммами по
       form->dgram_len — тем же видом, каким ходит человек. План, снятый с
       клиента, подтверждается его же формой, иначе «подтверждено» достаётся
       зонду. */
    const d2k_quic_form *form;
    uint32_t    mark;      /* SO_MARK на сокете; 0 — не метить */
    /* УЖЕ ЗАНЯТЫЙ сокет (d2k_props_bind_udp): его местный порт вызывающий
     * назвал датапату заранее, чтобы пробный план достался только этому
     * потоку. Ноль или меньше — завести свой; нулём сюда попадает структура,
     * обнулённая memset, и это правильный смысл: дескриптор ноль — это
     * стандартный ввод, зондом он не бывает. Владение переходит сюда. */
    int         use_fd;
    /* ВОЗДЕЙСТВИЕ ПЕРЕД ПЕРВЫМ INITIAL (замер плеча, задача 39). NULL —
     * Initial уходит сам. Иначе вызывается один раз с готовой датаграммой
     * первого Initial: 0 — хук отправил своё (фальшивки, TTL), и Initial
     * отправит соединение; 1 — хук отправил и сам Initial (фрагментами);
     * меньше нуля — отказ, соединение не поднимается. Повторы по таймеру
     * хук не видят. */
    int       (*first_send)(int fd, const uint8_t *initial, size_t len, void *user);
    void       *first_send_user;
} d2k_qc_opts;

/* Поднимает соединение и доводит рукопожатие до прикладных ключей.
 * 0 — готово, -1 — сетевой отказ, -2 — локальный отказ настройки сокета. */
int d2k_qc_connect(const d2k_qc_opts *o, d2k_qc **out, char *err, size_t errcap);

/* ПЕРВЫЙ INITIAL КЛИЕНТА — БАЙТАМИ, без соединения: тот же пакет, с которого
 * d2k_qc_connect начинает рукопожатие (ClientHello с именем sni, ALPN h3,
 * транспортные параметры, добивка до 1200 байт по RFC 9000 §14.1), со своими
 * случайными DCID/SCID и ключом.
 *
 * Нужен приманкой. НЕ использовать как измерительный вход оригинала:
 * для него существует d2k_quic_probe_initial (d2k_quichello.h).
 * Коробка, узнающая протокол по первому пакету потока,
 * принимает такой поток за QUIC. Боевой профиль голоса z2k ставит для этого
 * чужой блоб (quic_dbankcloud); здесь пакет свой. 0 — собран, out_len — его
 * длина; -1 — не собрался или не влез в cap. */
int d2k_qc_first_initial(const char *sni, uint8_t *out, size_t cap, size_t *out_len);

/* Шлёт данные потоком stream_id в одном пакете 1-RTT. 0 — ушло, -1 — отказ с
 * причиной в err. Среди причин — ПРЕДЕЛ, ОБЪЯВЛЕННЫЙ СЕРВЕРОМ (потоков или
 * данных): это не неудача на проводе, а замер, который не состоится, и причина
 * так и названа — чтобы в журнале стояла она, а не «сеть». */
int d2k_qc_stream_send(d2k_qc *c, uint64_t stream_id, const uint8_t *data, size_t n,
                       int fin, char *err, size_t errcap);

/* Ждёт данных ЛЮБОГО потока не дольше wait_ms и складывает их в buf.
 * Возвращает число прочитанных байт (>0), 0 — за это время ничего не пришло,
 * -1 — соединение закрыто или отказ. stream_out — номер потока, чьи данные
 * вернулись (значим при возврате > 0). */
long d2k_qc_stream_recv(d2k_qc *c, uint64_t *stream_out, uint8_t *buf, size_t cap,
                        int wait_ms, char *err, size_t errcap);

/* Сколько байт датаграмм соединение приняло от сервера за всё время (все
 * уровни, включая неразобранное). Разность до и после запроса отличает
 * «сервер замолчал» от «сервер говорит, но не отвечает». */
uint64_t d2k_qc_rx_wire_bytes(const d2k_qc *c);

/* Датаграммы связи: отправленные (tx) и принятые (rx), с рукопожатием.
 * Бюджет коробки считается пакетами (задача 55). */
void d2k_qc_datagrams(const d2k_qc *c, uint64_t *tx, uint64_t *rx);

/* ДАННЫЕ ОТВЕТА НА НАШ ЗАПРОС, прошедшие линию после рукопожатия: bytes —
 * сколько разных байт потока запроса принято под прикладными ключами (не
 * только то, что поместилось в буфер чтения); complete — FIN принят и все
 * байты от нуля до смещения FIN пришли без дыр: ответ целиком. */
void d2k_qc_app_progress(const d2k_qc *c, uint64_t *bytes, int *complete);

/* Совпало ли имя в сертификате сервера с тем, что спросили: 1 да, 0 НЕТ,
 * -1 сказать нечего. Смысл тот же, что у d2k_tls_peer_name: это НЕ проверка
 * подлинности. */
int d2k_qc_peer_name(const d2k_qc *c);

/* Получил ли сервер HANDSHAKE_DONE — то есть рукопожатие подтверждено им
 * самим, а не только нами. */
int d2k_qc_handshake_done(const d2k_qc *c);
/* RTT рукопожатия, мс: от первого Initial до первой датаграммы сервера
   (0 — не измерен). Задача 50, раунд 3. */
int64_t d2k_qc_rtt_ms(const d2k_qc *c);
/* Датаграммы соединения в обе стороны (задача 50, раунд 4: бюджет коробки). */
void d2k_qc_dgrams(const d2k_qc *c, uint64_t *tx, uint64_t *rx);
/* PING под прикладными ключами — кадр, требующий подтверждения: живой сервер
   отвечает на него за RTT + max_ack_delay (RFC 9000 §19.2). */
int d2k_qc_ping(d2k_qc *c, char *err, size_t errcap);

/* ДОХОДЯТ ЛИ НАШИ ПАКЕТЫ ДО СЕРВЕРА — отдельный факт от «сервер нам шлёт».
 *
 * sent_pn — номер последнего ОТПРАВЛЕННОГО нами пакета уровня приложения;
 * acked_pn — наибольший номер НАШЕГО пакета, подтверждённый сервером в кадре
 * ACK. Возвращает 1, если подтверждение было хоть раз (нулевой номер пакета
 * законен, поэтому признак отдельный), иначе 0 и acked_pn не задан.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ d2k_qc_rx_wire_bytes. Оба известных цензора QUIC роняют
 * пакеты ТОЛЬКО в исходящем направлении (Россия: FOCI 2026(2) §3, остаточная
 * блокировка 420 с по четвёрке, in-path; Китай: USENIX Security 25, 180 с).
 * Когда исходящее направление заглушено, сервер продолжает повторять свой
 * последний полёт по таймеру PTO (RFC 9002 §6.2) — входящие датаграммы и
 * байты РАСТУТ, и по ним связь выглядит живой. Единственное, что перестаёт
 * расти, — подтверждения наших пакетов. Поле 12.10.2026: стенд повторов
 * выдавал «сервер ответил на каждый, 32 547 из 50 датаграмм» на связи, где
 * сервер не получил от нас ни одного пакета. */
int d2k_qc_outbound(const d2k_qc *c, uint64_t *sent_pn, uint64_t *acked_pn);

/* Местный конец соединения: по нему датапат привязывает событие к потоку.
 * Порт в машинном порядке. */
void d2k_qc_local(const d2k_qc *c, uint8_t ip4[4], uint16_t *port);
void d2k_qc_local_addr(const d2k_qc *c, uint8_t addr[16], uint8_t *family,
                       uint16_t *port);

/* Сокет остаётся ОТКРЫТЫМ до d2k_qc_close — по той же причине, что у
 * TCP-зонда: закрытие удаляет ячейку потока в датапате раньше, чем придёт
 * событие применения плана. */
int  d2k_qc_fd(const d2k_qc *c);

/* Освобождает состояние соединения, НЕ ЗАКРЫВАЯ сокет, и возвращает его.
 * Нужна зонду: решение по обращению принимает планировщик, и до этого момента
 * поток обязан жить — закрытие удаляет ячейку в датапате раньше, чем придёт
 * событие применения плана. Дальше сокет закрывает тот, кто его взял. */
int  d2k_qc_release(d2k_qc *c);

void d2k_qc_close(d2k_qc *c);

#endif /* D2K_QUICCONN_H */
