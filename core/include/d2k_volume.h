/* d2k_volume.h — направленные пробы блокировки по объёму соединения.
 *
 * ИЗМЕРЯЮТСЯ ДВА НЕСЛИВАЕМЫХ НАПРАВЛЕНИЯ. TX-лестница накачивает запросы
 * клиента (унаследованный probe), RX-проба читает HTTP-тело ответа. Для RX
 * обрыв считается особым классом только если два identity-ответа с одинаковым
 * Content-Length/chunked framing обрываются на близком объёме, а контроль,
 * действительно полученный в gzip, завершается — либо (пакетный бюджет,
 * поле 04.10) gzip обрывается тоже, но на том же числе пакетов с данными.
 * До HTTP-заголовков отдельно мерится незавершённая TLS-запись: два HTTP0
 * с одинаковой согласованной версией, близким RX wire объёмом и меньшим
 * полным gzip дают rx-volume-wire. Ciphertext и HTTP-body не смешиваются.
 * Приметы tx-volume, rx-volume и rx-volume-wire хранятся отдельно; действие из одной пробы не
 * объявляется лечением другой, пока кандидат не подтвердит собственный зонд.
 *
 * ПОЧЕМУ ПРОБА, А НЕ НАБЛЮДЕНИЕ ЗА ЧУЖИМ ТРАФИКОМ. Наблюдение отвечает на
 * вопрос «этот хост сейчас режут?» и ошибается в обе стороны: горизонт
 * видимости датапата — первые пакеты соединения, и здоровая крупная загрузка
 * выглядит оттуда ровно как обрыв. Проба отвечает на другой вопрос — «есть ли
 * этот блок на ЭТОЙ линии к ЭТОЙ сети» — за секунды, на своей мишени, своим
 * объёмом и не трогая пользовательский трафик.
 *
 * ЗАЧЕМ ПРОБА ИДЁТ ПЕРВОЙ. Пока результат направленного измерения неизвестен,
 * обычная классификация может приписать обрыв TLS рукопожатию/имени, хотя
 * соединение обрывается в теле ответа. Измерение даёт отдельную улику, не
 * отключая общий перебор: сохранённые планы коробки идут первыми, за ними —
 * подходящий объёмному профилю кандидат, затем остальные планы.
 *
 * TX-лестница перенесена из internal/volume (Go), z2k, 31.08.2026,
 * runnin4ik/dpi-detector. RX-пара identity/gzip добавлена отдельно по
 * наблюдению RuTracker: незжатое тело стабильно обрывалось около 23,9 КБ,
 * gzip-ответ завершался. Само наблюдение цели не фиксируется в коде.
 */
#ifndef D2K_VOLUME_H
#define D2K_VOLUME_H

#include <stddef.h>
#include <stdint.h>
#include "d2k_verify.h"

/* Ступень лестницы объёма и число ступеней: накопленный объём растёт
 * 4, 8, 12 … 40 КБ и покрывает весь наблюдавшийся разброс обрыва. */
#define D2K_VOL_CHUNK  4000
#define D2K_VOL_STEPS  10

/* Ниже этого объёма обрыв нашим классом не считается. До двенадцати килобайт
 * соединения рвутся по десятку обычных причин, и вердикт был бы шумом, а не
 * измерением. */
#define D2K_VOL_MIN_KB 12

/* Разброс пакетного бюджета одной коробки: обрывы identity и gzip считаются
 * одним бюджетом, если пакеты с данными на них расходятся не больше чем на
 * столько. Поле 04.10 (task-55-facts §1.2): 25–27 в 18/18 потоках. */
#define D2K_VOLUME_PACKET_SLACK 3

typedef enum {
    /* Мишень не ответила вовсе. Про линию не сказано ничего: это НЕ «блока
       нет». */
    D2K_VOL_UNREACHABLE = 0,
    /* Соединение умерло за порогом. Это наш класс. */
    D2K_VOL_CUT,
    /* Лестница пройдена целиком, соединение живо. */
    D2K_VOL_PASSED,
    /* Объём до порога не дорос: документ кончился раньше или обрыв случился
       слишком рано. Вердикта НЕТ, и выдавать это за «блока нет» нельзя. */
    D2K_VOL_SHORT
} d2k_vol_verdict;

typedef struct {
    d2k_vol_verdict verdict;
    int      at_kb;       /* накопленный объём, на котором всё кончилось */
    int      rx_cut;      /* paired identity/gzip response cut, domain given by rx_wire_basis */
    int      rx_at_kb;    /* body bytes, or TLS wire bytes iff rx_wire_basis */
    int      rx_wire_basis; /* distinct rx-volume-wire signal, never compared to body size */
    int      rx_expected_kb; /* Content-Length, если известен */
    /* Пакеты с данными обеих сторон на обрыве identity (TCP_INFO) — бюджет
       потока коробки (задача 55); 0 — не посчитаны. */
    int      rx_cut_packets;
    int      rx_compressed_complete; /* контроль gzip дошёл до конца */
    int      rtt_ms;      /* измеренный RTT до мишени */
    char     reason[160]; /* человеческая причина, заполняется всегда */
    char     rx_reason[256]; /* отдельный исход GET, даже если TX не дошёл до TLS */
    int      rx_tls_unavailable; /* прямой GET не дошёл до TLS; RX-тела ещё не измерить */
    /* ОТВЕТ ЗОНДА ЗАВЕРШИЛСЯ, НЕ ДОЙДЯ ДО ИЗМЕРЯЕМОЙ ПОЛОСЫ: бюджет объёма
     * НЕ ПРОВЕРЕН. Это D2K_VOL_SHORT в домене RX, то есть отсутствие
     * измерения, а НЕ парное отрицательное измерение обрыва. Поле 12.10.2026,
     * soundcloud: зонд просил / и получал 403 с телом 263 байта и 401 с
     * пустым телом, complete=1, тогда как живые потоки замерзали на 23–25 КБ.
     * Прежде чем отдать это наверх, зонд ОДИН раз повторяет замер по другому
     * публичному пути того же имени, если тот же ответ его назвал: размер
     * ресурса заранее неизвестен, поэтому «обещает объём» не заявляется —
     * объём выясняет повторное измерение. Подсказки нет или повтор тоже
     * ничего не измерил — rx_short остаётся, с байтами первого ответа. */
    int      rx_short;
    uint64_t rx_short_bytes; /* тело того завершённого ответа, для журнала */
    /* TLS установлен, но RX не дал завершённого ответа или измеримого среза. */
    int      rx_unmeasured;
    /* ПУТЬ, НА КОТОРОМ ОБРЫВ ИЗМЕРЕН. Заполняется вместе с rx_cut и только
     * тем путём, который зонд действительно спрашивал, — в том числе путём
     * повтора по подсказке (resource_retry_path): дальше по ЭТОМУ пути обязаны
     * идти зонд кандидата и следующий эпизод, иначе «/» того же CDN-хоста
     * отдаст завершённый 403 на несколько сотен байт и доказанный обрыв не
     * превратится в подтверждённое решение.
     *
     * ПУСТО — измерения обрыва не было ВОВСЕ либо оно шло по умолчательному
     * «/», который вызывающий и так знает: отличать одно от другого по этому
     * полю нельзя, для этого есть rx_cut и rx_short. Непустое значение — адрес
     * измерения и НИЧЕГО больше: ни обещания объёма по этому пути, ни
     * подтверждения плана, ни права спрашивать этот путь у другого имени.
     *
     * TX-лестница сюда не пишет: она накачивает СВОЙ объём запросами «HEAD /»
     * и про путь ресурса не говорит ничего — её обрыв (verdict) к пути не
     * привязан. */
    char     measured_path[512];
    int      rx_direct_complete; /* identity response fully received with matching certificate */
    uint64_t rx_partial_bytes; /* first framed partial RX body; not a paired verdict */
    uint64_t rx_partial_wire_bytes; /* first incomplete TLS record progress; separate domain */
    d2k_resource resources[D2K_RESOURCE_COUNT];
    size_t n_resources;
} d2k_vol_result;

/* Гоняет TX-лестницу, затем для HTTPS — парное RX-измерение тела ответа.
 * ip:port, имя sni предъявляется в TLS (пустое — идём по адресу). plain != 0
 * — открытый HTTP, без рукопожатия; отдельным параметром, а не выводом из
 * номера порта. tls12 и hello_wire выбирают форму baseline-зонда клиента.
 *
 * mark — метка SO_MARK (0 — не метить). Здесь она НУЖНА, в отличие от зонда
 * свойств: проба меряет ЛИНИЮ, а не работу плана, и уже поставленный план
 * исказил бы её. */
d2k_vol_result d2k_volume_probe(const char *ip, uint16_t port, const char *sni,
                                int plain, int tls12, size_t hello_wire,
                                uint32_t mark);
d2k_vol_result d2k_volume_probe_path(const char *ip, uint16_t port, const char *sni,
    int plain, int tls12, size_t hello_wire, uint32_t mark, const char *path);

/* Чистая проверка трёх уже полученных ответов: две повторные identity-обрезки
 * и полный gzip-контроль. Нужна также тестам, чтобы границы RX-диагноза были
 * проверяемы без сетевых прогонов. Возвращает 1 только при подтверждённой
 * асимметрии и заполняет RX-поля out, иначе 0. */
int d2k_volume_rx_evidence(const d2k_ver_result *identity_a,
                           const d2k_ver_result *identity_b,
                           const d2k_ver_result *gzip_control,
                           d2k_vol_result *out);
/* Suspicion only, never a blocking verdict without repeat + gzip control. */
int d2k_volume_rx_partial(const d2k_ver_result *identity);

/* Оба измерения оборваны в одном домене и в одном его контексте, то есть
 * сопоставимы. Байты и допуск — дело d2k_volume_rx_evidence. */
int d2k_volume_rx_pair_agrees(const d2k_ver_result *a, const d2k_ver_result *b);

/* Первое измерение оборвано, второе ЗАВЕРШИЛОСЬ кодом 2xx, само пройдя
 * измеряемую полосу: измерения расходятся, и нужен третий identity-прогон.
 * Вердикт по-прежнему требует двух обрывов — третий прогон не ослабляет
 * правило, а решает расхождение. Поле 12.10.2026, www.tampermonkey.net:
 * /style.css рвётся 8 раз из 8 (15963 против 30182 с VPS), а один дошедший
 * повтор зонда отправлял цель на покой. Пустое измерение и завершённый
 * ответ меньше полосы повтора НЕ заказывают. */
int d2k_volume_rx_needs_repeat(const d2k_ver_result *a, const d2k_ver_result *b);

const char *d2k_vol_verdict_name(d2k_vol_verdict v);

#endif /* D2K_VOLUME_H */
